"""IE DLG / BCS -> Temple+ dialogue + Python script converter (pilot).

Runs on the player's machine against their own IE install: the output (dialog text, script logic, resource
names) is derived from the game and must stay local. Nothing produced here is shipped.

    python3 ie_dialogue.py <IE dir> <out dir> --actor IDENT:AREA:SCRIPT_ID[:DLG][:BCS,BCS...] ...
                          [--area-script AREA:BCS] [--tlk dialog.tlk] [--fallback iesdp_opcodes.json]
                          [--slot-base 1000]

Output (<out>/modules/ToEE/...):  dlg/NNNNNie_<ident>.dlg   scr/pyNNNNNie_<ident>.py   scr/ie_bcs_<res>.py
                                  scr/ie_varslots.py (persistent variable slots)   report.json
The scr/ folder also needs proto/runtime/ie_runtime.py.
"""
import os, re, json, argparse, math
import iefs, iescript as S
from iecodegen import Gen, pystr

HEADER = '# -*- coding: cp1252 -*-\n# Generated by ie2toee ie_dialogue.py from the player\'s own IE install. Do not distribute.\n'

# IE text tokens -> (male, female) replacement; ToEE expands @pcname@ itself
TOKENS = {
    'CHARNAME': ('@pcname@', '@pcname@'), 'GABBER': ('@pcname@', '@pcname@'), 'PLAYER1': ('@pcname@', '@pcname@'),
    'PRO_HESHE': ('he', 'she'), 'PRO_HIMHER': ('him', 'her'), 'PRO_HISHER': ('his', 'her'),
    'PRO_MANWOMAN': ('man', 'woman'), 'PRO_BOYGIRL': ('boy', 'girl'), 'PRO_SIRMAAM': ('sir', "ma'am"),
    'SIRMAAM': ('sir', "ma'am"), 'LADYLORD': ('lord', 'lady'), 'PRO_LADYLORD': ('lord', 'lady'),
    'PRO_BROTHERSISTER': ('brother', 'sister'), 'BROTHERSISTER': ('brother', 'sister'),
    'PRO_GIRLBOY': ('boy', 'girl'), 'MALEFEMALE': ('male', 'female'),
}

def subst(text, female):
    def rep(m):
        t = TOKENS.get(m.group(1).upper())
        return t[1 if female else 0] if t else m.group(0)
    t = re.sub(r'<([A-Z_0-9]+)>', rep, text)
    t = t.replace('{', '(').replace('}', ')').replace('\r', '').replace('\n', ' ')
    return ascii_text(t)

# ToEE's fonts are plain ASCII: fold the IE (EE: Unicode) typography so no '?'/box glyphs show up
_FOLD = [(re.compile(r'\s*[\u2014\u2015]\s*'), ' - '), (re.compile(r'\s*\u2013\s*'), ' - '),
         (re.compile('[\u2018\u2019\u201a\u2032]'), "'"), (re.compile('[\u201c\u201d\u201e\u2033]'), '"'),
         (re.compile('\u2026'), '...'), (re.compile('[\u00a0\u2009\u200a\u2002\u2003]'), ' ')]

def ascii_text(t):
    for rx, r in _FOLD:
        t = rx.sub(r, t)
    return t

# The logbook (temple.dll) hangs on long quest descriptions (vanilla's longest is 214 chars): cut at a sentence end
DESC_MAX = 250

def cap_desc(t, n=DESC_MAX):
    if len(t) <= n:
        return t
    cut = t[:n]
    i = max(cut.rfind('. '), cut.rfind('! '), cut.rfind('? '))
    return cut[:i + 1] if i > n // 3 else cut[:n - 3].rsplit(' ', 1)[0] + '...'

_STOP = set('the a an and or of to in on at for with we us our was were is be been that this his her he she it its from by as but have has had they them their there into out not will would who which what when then than so'.split())

def _words(t):
    return set(w for w in re.findall(r"[a-z][a-z'-]{2,}", t.lower()) if w not in _STOP)

def merge_journals(journals, origin, text, jvars=None, jerase=None):
    """IE has one journal entry per step; ToEE one quest per id. A solved ('done') entry joins an opening ('quest')
    entry. First by trace: the opening that the same action list erases (AddJournalEntry(done) +
    EraseJournalEntry(opening), IE's own "this step replaces that one"); then the openings whose dialogue/script tests or sets a variable that the done entry's own
    dialogue/script also tests or sets (vars seen beside more than 4 entries are too generic and ignored); several
    such openings -> most shared words. Fallback, no shared variable: word similarity (clear winner only).
    Returns {done strref: (opening strref, 'vars' | 'words')}."""
    jvars = jvars or {}
    opens = [r for r, k in journals.items() if k == 'quest']
    cnt = {}
    for r in journals:
        for v in jvars.get(r, ()):
            cnt[v] = cnt.get(v, 0) + 1
    jv = dict((r, set(v for v in jvars.get(r, ()) if cnt[v] <= 4)) for r in journals)
    def sim(a, b):
        wa, wb = _words(text(a)), _words(text(b))
        return len(wa & wb) / float(len(wa | wb) or 1)
    out = {}
    for r, k in journals.items():
        if k != 'done':
            continue
        er = [o for o in opens if o in (jerase or {}).get(r, ())]
        if er:
            out[r] = (max(er, key=lambda o: sim(r, o)), 'erase')
            continue
        traced = [o for o in opens if jv[r] & jv[o]]
        if traced:
            out[r] = (max(traced, key=lambda o: (len(jv[r] & jv[o]), sim(r, o))), 'vars')
            continue
        best = (0.0, None); second = 0.0
        for o in opens:     # same dialogue/script: 0.12 overlap is enough; elsewhere 0.14
            same = bool(origin.get(o, set()) & origin.get(r, set()))
            sc = sim(r, o) - (0 if same else 0.02)
            if sc > best[0]:
                best, second = (sc, o), best[0]
            elif sc > second:
                second = sc
        if best[1] is not None and (best[0] >= 0.12 or (best[0] >= 0.08 and best[0] >= 1.5 * second)):
            out[r] = (best[1], 'words')
    return out

def _stride(dlg):
    m = max([s['count'] for s in dlg.states] + [1])
    return 10 ** int(math.ceil(math.log10(m + 2)))

class DlgConv(object):
    def __init__(self, game, ids, text, ident, area, gen):
        self.game, self.ids, self.text, self.ident, self.area, self.g = game, ids, text, ident, area, gen
        self.dlgs = []        # [(resref, Dlg, base)]
        self.notes = []

    def load(self, resref):
        for r, d, b in self.dlgs:
            if r == resref:
                return b, d
        d = S.Dlg(self.game.read(resref, 'dlg'), resref)
        base = 0 if not self.dlgs else (len(self.dlgs)) * 20000
        if self.dlgs:
            self.notes.append('cross-dialogue jump into %s (speaker change not modelled; same NPC speaks)' % resref)
        self.dlgs.append((resref, d, base))
        return base, d

    def line(self, resref, state):
        base, d = self.load(resref)
        return base + (state + 1) * _stride(d)

    def parse(self, s):
        try:
            return S.parse_script_text(s, list(self.ids['object'].by_name))
        except SyntaxError as e:
            self.notes.append('unparsed script text: %s' % e)
            return None

    def convert(self, resref):
        out_lines, funcs, states = [], [], []
        self.load(resref)
        i = 0
        while i < len(self.dlgs):              # dialogues reached through transitions are appended while we go
            r, d, base = self.dlgs[i]; i += 1
            st = _stride(d)
            for si, s in enumerate(d.states):
                L = base + (si + 1) * st
                txt = self.text(s['text'])
                out_lines.append('{%d}{%s}{%s}{}{}{}{}' % (L, subst(txt, False), subst(txt, True)))
                trs = list(range(s['first'], s['first'] + s['count']))
                if not trs:
                    out_lines.append('{%d}{[End dialogue]}{}{1}{}{0}{}' % (L + 1))
                for k, ti in enumerate(trs):
                    t = d.transitions[ti]
                    tl = L + 1 + k
                    if t['text'] is not None:
                        pt = subst(self.text(t['text']), False)
                    else:
                        pt = '[End dialogue]' if t['end'] else '[Continue]'
                    test = effect = ''
                    if t['trigger'] is not None:
                        calls = self.parse(d.trans_trigger(ti))
                        if calls:
                            fn = 'ie_c%d' % tl
                            funcs.append('def %s(npc, pc):\n    return rt.dlg_cond(npc, pc, IDENT, AREA, lambda c: %s)\n'
                                         % (fn, self.g.condition(calls)))
                            test = '%s(npc, pc)' % fn
                    acts = self.parse(d.trans_action(ti)) if t['action'] is not None else []
                    jour = None
                    if t['journal'] is not None and t['journal'] > 0:    # flags: bit 6 unsolved quest, 7 info, 8 solved
                        fl_ = t['flags']
                        kind = 'done' if fl_ & 256 else 'info' if fl_ & 128 else 'quest'
                        self.g.journals.setdefault(t['journal'], kind); self.g.strrefs.add(t['journal'])
                        jour = (t['journal'], kind)
                        self.g.note_journal_vars(t['journal'], (acts or []) + (self.parse(d.trans_trigger(ti)) or [] if t['trigger'] is not None else [])
                                                 + (self.parse(d.state_trigger(si)) or [] if s['trigger'] is not None else []))
                    if acts or jour:
                        fn = 'ie_a%d' % tl
                        funcs.append('def %s(npc, pc):\n    return rt.dlg_do(npc, pc, IDENT, AREA, %s, journal=%s)\n'
                                     % (fn, self.g.action_list(acts or []), repr(jour) if jour else 'None'))
                        effect = '%s(npc, pc)' % fn
                    ans = 0 if t['end'] else self.line(t['next_dlg'] or r, t['next_state'])
                    if any(getattr(a_, 'name', '').lower() == 'startstore' for a_ in acts):
                        pt = 'B:' + pt      # ToEE opens the barter screen on "B:" responses (vanilla merchants)
                    out_lines.append('{%d}{%s}{}{1}{%s}{%d}{%s}' % (tl, pt, test, ans, effect))
                out_lines.append('')
        # entry: states with triggers, in state-trigger-table order (the IE checks them in that order)
        _, d, base = self.dlgs[0]; st = _stride(d)
        order = sorted([(s['trigger'], si) for si, s in enumerate(d.states) if s['trigger'] is not None])
        for trig, si in order:
            calls = self.parse(d.state_trigger(si))
            if calls is None:
                continue
            states.append('    (%d, lambda c: %s),' % (base + (si + 1) * st, self.g.condition(calls)))
        targets = set(t['next_state'] for t in d.transitions if not t['end'] and (t['next_dlg'] or resref) == resref)
        roots = [si for si, s in enumerate(d.states) if s['trigger'] is None and si not in targets]
        entry = base + (roots[0] + 1) * st if roots else None
        return out_lines, funcs, states, entry

def bcs_module(game, ids, resref, ident, area, gen):
    b = S.Bcs(game.read(resref, 'bcs'), ids, resref)
    src = [HEADER, 'import ie_runtime as rt\nfrom ie_runtime import T, A, O, N, F\n',
           'RESREF = %s\n' % pystr(resref), 'BLOCKS = [']
    for trig, resp in b.blocks:
        cond = gen.condition(trig)
        rs = ', '.join('(%d, %s)' % (w, gen.action_list(acts)) for w, acts in resp)
        src.append('    (lambda c: %s,\n     [%s]),' % (cond, rs))
    src.append(']\n')
    casts = any(re.search(r'\bA\.(Spell|ForceSpell|ReallyForceSpell|ApplySpell|SpellPoint|ForceSpellPoint)', x) for x in src)
    src.append('CASTS = %r   # the script casts spells (SPL-ADJ-18)\n' % casts)
    return '\n'.join(src), len(b.blocks), sorted(b.unknown)

def actor_script(sid, ident, area, dlg_parts, bcs_mods):
    src = [HEADER, 'from toee import *\nimport ie_runtime as rt\nfrom ie_runtime import T, A, O, N, F\n']
    src.append('IDENT = %s\nAREA = %s\n' % (pystr(ident), pystr(area)))
    src.append('SCRIPTS = []\n')
    for m in bcs_mods:
        src.append('import %s\nSCRIPTS.append(%s)\n' % (m, m))
    if dlg_parts:
        lines, funcs, states, entry = dlg_parts
        src.append('STATES = [\n%s\n]\nENTRY = %r\n' % ('\n'.join(states), entry))
        src.append('def san_dialog(attachee, triggerer):\n'
                   '    return rt.dlg_start(attachee, triggerer, IDENT, AREA, STATES, ENTRY)\n')
        src.append('\n'.join(funcs))
    src.append('def san_heartbeat(attachee, triggerer):\n'
               '    if SCRIPTS:\n        rt.tick(attachee, IDENT, AREA, SCRIPTS)\n    return RUN_DEFAULT\n')
    src.append('def san_first_heartbeat(attachee, triggerer):\n'
               '    rt.bind(attachee, IDENT, AREA)\n    return RUN_DEFAULT\n')
    for san, ev in (('san_dying', 'Die'), ('san_enter_combat', 'AttackedBy')):
        src.append('def %s(attachee, triggerer):\n    rt.event(IDENT, %s, triggerer)\n    return RUN_DEFAULT\n'
                   % (san, pystr(ev)))
    # each combat turn: one IE script round with engine feasibility checks (runtime/ie_combat.py); the first feasible
    # block's Spell/Attack becomes the turn's Temple+ strategy, else the converted static strategy (both end in "stop")
    src.append('def san_start_combat(attachee, triggerer):\n    rt.event(IDENT, "AttackedBy", triggerer)\n'
               '    if SCRIPTS:\n        return rt.combat_round(attachee, IDENT, AREA, SCRIPTS)\n'
               '    return RUN_DEFAULT\n')
    return '\n'.join(src)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('game'); ap.add_argument('out')
    ap.add_argument('--actor', action='append', default=[], help='IDENT:AREA:SCRIPT_ID[:DLG][:BCS,BCS]')
    ap.add_argument('--area-script', action='append', default=[], help='AREA:BCS')
    ap.add_argument('--tlk'); ap.add_argument('--lang', help='EE locale, e.g. en_US'); ap.add_argument('--fallback'); ap.add_argument('--slot-base', type=int, default=1000)
    ap.add_argument('--area-map', action='append', default=[], help='AREA:TOEE_MAP[:canvas_x,canvas_y]')
    ap.add_argument('--slot-max', type=int, default=1999)
    ap.add_argument('--quest-base', type=int, default=120, help='first ToEE quest id for IE journal entries (vanilla: 0-60)')
    ap.add_argument('--quest-max', type=int, default=199, help='last one (the logbook has 200 quests)')
    a = ap.parse_args()
    game = iefs.IEGame(a.game)
    ids = S.IdsSet(game, json.load(open(a.fallback)) if a.fallback else None)
    tlk = None
    if a.tlk:
        tlk = S.Tlk.load(a.tlk)
    else:
        p = S.find_tlk(a.game, a.lang)
        tlk = S.Tlk.load(p) if p else None
    text = S.StrrefText(tlk)
    mod = os.path.join(a.out, 'modules', 'ToEE'); scr = os.path.join(mod, 'scr'); dlgd = os.path.join(mod, 'dlg')
    for d in (scr, dlgd):
        os.makedirs(d, exist_ok=True)
    rep = {'tlk': bool(tlk), 'ids_missing': ids.missing, 'actors': [], 'area_scripts': [], 'unknown': {}}
    allvars = set(); strrefs = set(); journals = {}; origin = {}; jvars = {}; jerase = {}
    def w(path, s):
        # ToEE reads Windows-1252 text; EE text outside it becomes '?'
        open(path, 'w', encoding='cp1252', errors='replace', newline='\r\n' if path.endswith('.dlg') else '\n').write(s)
    done_bcs = {}
    def bcs(res, ident, area):
        g = Gen(ids, ident, area)
        src, nb, unk = bcs_module(game, ids, res, ident, area, g)
        m = 'ie_bcs_%s' % re.sub(r'\W', '_', res.lower())
        if ident.startswith('area_'):
            m += '_area'
        w(os.path.join(scr, m + '.py'), src)
        allvars.update(g.vars); rep['unknown'].update(g.unknown); strrefs.update(g.strrefs); journals.update(g.journals); [jvars.setdefault(r_, set()).update(v_) for r_, v_ in g.jvars.items()]; [jerase.setdefault(r_, set()).update(v_) for r_, v_ in g.jerase.items()]; [origin.setdefault(r_, set()).add(ident) for r_ in g.journals]
        return m, nb, unk
    for spec in a.actor:
        parts = spec.split(':') + ['', '']
        ident, area, sid, dlg, bl = parts[0], parts[1].upper(), int(parts[2]), parts[3].lower(), parts[4].lower()
        g = Gen(ids, ident, area)
        dlg_parts = None; notes = []
        if dlg:
            dc = DlgConv(game, ids, text, ident, area, g)
            dlg_parts = dc.convert(dlg); notes = dc.notes
            g.vars.add(g.var_key('#talked', 'LOCALS'))     # dlg_start always counts conversations
            w(os.path.join(dlgd, '%05die_%s.dlg' % (sid, ident.lower())), '\n'.join(dlg_parts[0]) + '\n')
        mods = []
        for res in [x for x in bl.split(',') if x]:
            m, nb, unk = bcs(res, ident, area); mods.append(m)
        w(os.path.join(scr, 'py%05die_%s.py' % (sid, ident.lower())), actor_script(sid, ident, area, dlg_parts, mods))
        allvars.update(g.vars); rep['unknown'].update(g.unknown); strrefs.update(g.strrefs); journals.update(g.journals); [jvars.setdefault(r_, set()).update(v_) for r_, v_ in g.jvars.items()]; [jerase.setdefault(r_, set()).update(v_) for r_, v_ in g.jerase.items()]; [origin.setdefault(r_, set()).add(ident) for r_ in g.journals]
        rep['actors'].append({'ident': ident, 'area': area, 'script_id': sid, 'dlg': dlg, 'bcs': mods,
                              'lines': len([l for l in (dlg_parts[0] if dlg_parts else []) if l]),
                              'entry_states': len(dlg_parts[2]) if dlg_parts else 0, 'notes': notes})
    for spec in a.area_script:
        area, res = spec.split(':')
        m, nb, unk = bcs(res.lower(), 'area_' + area.upper(), area.upper())
        rep['area_scripts'].append({'area': area.upper(), 'module': m, 'blocks': nb})
    keys = sorted(allvars)
    if len(keys) > a.slot_max - a.slot_base + 1:
        raise SystemExit('too many variables (%d) for slots %d..%d' % (len(keys), a.slot_base, a.slot_max))
    slots = dict((k, a.slot_base + i) for i, k in enumerate(keys))
    w(os.path.join(scr, 'ie_varslots.py'), HEADER + 'SLOTS = {\n%s\n}\n' %
      '\n'.join('    %s: %d,' % (pystr(k), v) for k, v in sorted(slots.items(), key=lambda kv: kv[1])))
    rep['vars'] = len(keys)
    w(os.path.join(scr, 'ie_strings.py'), HEADER + 'STRINGS = {\n%s\n}\n' %
      '\n'.join('    %d: %s,' % (r, pystr(subst(text(r), False))) for r in sorted(strrefs)))
    # journal entries -> ToEE logbook quests (mes/gamequestlog.mes: title at id, description at id + 200)
    qids = list(range(a.quest_base, a.quest_max + 1)); jmap = {}; jl = []
    merged = merge_journals(journals, origin, text, jvars, jerase)
    for r in sorted(r for r in journals if r not in merged):
        if not qids:
            print('warning: more journal entries than quest slots %d..%d: %d dropped' % (a.quest_base, a.quest_max, len(journals) - len(jmap)))
            break
        q = qids.pop(0); body = subst(text(r), False).replace('{', '(').replace('}', ')')
        lines_ = [x.strip() for x in body.replace('\r', '').split('\n') if x.strip()]
        title = lines_[0] if lines_ else 'Journal'
        if len(title) > 60:
            title = title[:57].rsplit(' ', 1)[0] + '...'
        jmap[r] = (q, journals[r])
        jl += ['{%d}{%s}' % (q, title), '{%d}{%s}' % (q + 200, cap_desc(' '.join(lines_)))]
    for r, (o, how) in sorted(merged.items()):
        if o in jmap:
            jmap[r] = (jmap[o][0], journals[r])
    rep['journal_merged'] = dict((r, list(merged[r])) for r in merged if r in jmap)
    w(os.path.join(scr, 'ie_journal.py'), HEADER + 'JOURNAL = %r   # strref -> (ToEE quest id, kind)\n' % jmap)
    with open(os.path.join(a.out, 'journal_snippets.txt'), 'w', encoding='cp1252', errors='replace') as f:
        f.write('# mes/gamequestlog.mes\n' + '\n'.join(l for l in jl if True) + '\n')
        f.write('# rules/gamequest.mes\n' + '\n'.join('{%d}{1}' % q for q in sorted(set(q for q, _ in jmap.values()))) + '\n')
    rep['journal'] = len(jmap)
    am = {}; pl = {}
    for spec in a.area_map:     # AREA:MAP[:cx,cy]
        f = spec.split(':')
        am[f[0].upper()] = int(f[1])
        if len(f) > 2:
            pl[f[0].upper()] = tuple(int(v) for v in f[2].split(','))
    xp = {}
    try:   # XPLIST.2DA (EE): rows used by AddXP2DA
        rows = game.read('xplist', '2da').decode('latin-1').splitlines()
        for ln in rows[3:]:
            f = ln.split()
            if len(f) >= 2 and f[1].lstrip('-').isdigit():
                xp[f[0].upper()] = int(f[1])
    except Exception:
        pass
    w(os.path.join(scr, 'ie_xp.py'), HEADER + 'XP = %r\n' % xp)
    w(os.path.join(scr, 'ie_areas.py'), HEADER + 'MAPS = %r\nPLACEMENTS = %r\n' % (am, pl))
    json.dump(rep, open(os.path.join(a.out, 'report.json'), 'w'), indent=1)
    print(json.dumps({k: v for k, v in rep.items() if k != 'unknown'}, indent=1))
    print('unknown names:', rep['unknown'])

if __name__ == '__main__':
    main()
