#!/usr/bin/env python3
"""Collect the travel regions and entrances of the converted areas into ie_travel_data.py (runtime/ie_travel.py reads it).

  python ie_exits.py <workdir> --area AR1000:5900 --area AR1001:5901 ... --out <dir>/ie_travel_data.py

<workdir> holds the <AREA>_objects.json files written by ie2toee.py. For every converted area the data holds the
map id, its travel regions (polygon in ToEE tile coordinates, destination area + entrance) and its entrances (the
arrival tile: ie2toee moved it onto walkable ground). Exits whose destination area is not converted are listed
(stdout) and flagged "dest_map: 0" so the runtime shows the one-time "not in the preview" note for them.
Output is Python 2.7-compatible (it is imported inside Temple+) and derived from the player's own install.
"""
import argparse, json, os, sys


def collect(workdir, areas, text=None):
    """areas: {AREA: map_id}; text: strref -> str (info point texts). Returns (data dict, [problem strings])."""
    data, problems = {}, []
    for area, mid in sorted(areas.items()):
        o = json.load(open(os.path.join(workdir, area + '_objects.json')))
        ents = {}
        for e in o['entrances']:
            au, av = e.get('arrival') or [int(e['toee'][0]), int(e['toee'][1])]
            ents[e['name'].upper()] = [au, av, e.get('orient', 0)]
        regs, infos = [], []
        for r in o['regions']:
            if r['type'] == 'info' and text and r.get('info') not in (None, 0, 0xFFFFFFFF):
                t = text(r['info'])
                if t and not t.startswith('[strref'):
                    infos.append(dict(name=r['name'], poly=[[round(float(x), 2), round(float(y), 2)] for x, y in r['poly']],
                                      text=t))
                continue
            if r['type'] != 'travel' or not r.get('dest_area'):
                continue
            dest = r['dest_area'].upper()
            r_ent = (r.get('dest_entrance') or '').upper()
            extra = dict((k, r[k]) for k in ('anchor',) if r.get(k))
            regs.append(dict(extra, name=r['name'], poly=[[round(float(x), 2), round(float(y), 2)] for x, y in r['poly']],
                             dest_area=dest, dest_entrance=r_ent))
        data[area] = dict(map=mid, entrances=ents, regions=regs, infos=infos)
    for area, d in sorted(data.items()):
        for r in d['regions']:
            dst = data.get(r['dest_area'])
            if dst is None:
                problems.append('%s %s -> %s: destination area not converted' % (area, r['name'], r['dest_area']))
                r['dest_map'] = 0
            elif r['dest_entrance'] not in dst['entrances']:
                problems.append('%s %s -> %s: destination has no entrance %s' % (area, r['name'], r['dest_area'], r['dest_entrance']))
                r['dest_map'] = 0
            else:
                r['dest_map'] = dst['map']
    return data, problems


def write(data, path):
    with open(path, 'w') as f:
        f.write("# generated by ie_exits.py from the player's own IE install - do not distribute\n")
        f.write('# AREAS[area] = {map, entrances {name: [tile u, tile v, orient]}, regions [{name, poly, dest_area, dest_entrance, dest_map}]}\n')
        f.write('AREAS = ' + repr(json.loads(json.dumps(data))).replace('true', '1') + '\n')
        f.write('BY_MAP = dict([(a["map"], n) for n, a in AREAS.items()])\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('workdir')
    ap.add_argument('--area', action='append', required=True, help='AREA:map_id (repeat)')
    ap.add_argument('--out', required=True)
    ap.add_argument('--ie', help='IE install (dialog.tlk for the info point texts)')
    a = ap.parse_args()
    text = None
    if a.ie:
        import iescript as S
        p = S.find_tlk(a.ie)
        text = S.StrrefText(S.Tlk.load(p)) if p else None
    areas = {x.split(':')[0].upper(): int(x.split(':')[1]) for x in a.area}
    data, problems = collect(a.workdir, areas, text)
    write(data, a.out)
    n = sum(len(d['regions']) for d in data.values())
    print('ie_exits: %d areas, %d travel regions, %d info points -> %s' % (len(data), n, sum(len(d['infos']) for d in data.values()), a.out))
    for p in problems:
        print('  exit not usable: ' + p)
    return 0


if __name__ == '__main__':
    sys.exit(main())
